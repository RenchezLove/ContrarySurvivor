//
// История: окна игры собраны в дизайнере, и Ринат правит их подписи мышкой. Код при этом
// ставил тексты «всегда, в обоих путях», считая правдой C++-структуру стиля, — и каждый запуск
// игры молча показывал не то, что владелец написал в WBP (жалобы 23–24.08 по окну согласия и
// окну поддержки автора). Правда формулировок — АССЕТ ВЛАДЕЛЬЦА.
//
// Правило одно на все окна: непустую подпись кубика код не перезаписывает НИКОГДА. Он только
// заполняет пустой кубик (свежесобранный ассет или только что добавленный кубик) и полностью
// распоряжается своим кодовым деревом-запаской, где дизайнера нет вовсе.
//
// ⚠ Признак «дерево наше» брать ИМЕННО у построения кодового дерева (bCodeTreeBuilt), а не у
// детекта дизайнера (bDesignerTree): детект живёт в NativeOnInitialized, а движок 5.5 зовёт её
// только при живом игровом контексте (UserWidget.cpp:159-163 — условие
// !IsDesignTime() && (PlayerContext.IsValid() || bCanCallInitializedWithoutPlayerContext)).
// Не отработала — bDesignerTree ещё false, и текст владельца был бы затёрт. Признак «мы это
// построили» безопасен в обе стороны: сомнение всегда трактуется в пользу владельца.
//
// ⚠ ЖИВЫЕ ДАННЫЕ (числа здоровья, названия предметов, реплики, цены) под это правило НЕ
// попадают: они не подпись владельца, а содержимое, и их ставит код. Граница простая — если
// строка меняется по ходу игры, это данные; если она всё время одна и та же, это подпись
// владельца. Смешанный случай («Качество картинки: высокое») делать шаблоном: неизменную часть
// берём из кубика владельца, значение подставляем через FText::Format.

#pragma once

#include "CoreMinimal.h"
#include "Components/TextBlock.h"

namespace ContraryOwnerText
{
	// true = писать в этот кубик можно: дерево построил код ЛИБО владелец оставил кубик пустым.
	inline bool CodeOwns(const UTextBlock* Block, bool bCodeTreeBuilt)
	{
		return Block != nullptr && (bCodeTreeBuilt || Block->GetText().IsEmpty());
	}

	// Основной вызов вместо голого SetText для ЛЮБОЙ статичной подписи окна.
	inline void SetIfCodeOwns(UTextBlock* Block, const FText& Text, bool bCodeTreeBuilt)
	{
		if (CodeOwns(Block, bCodeTreeBuilt))
		{
			Block->SetText(Text);
		}
	}

	// Запомнить подпись, с которой окно пришло из дизайнера. Зовётся ОДИН раз и ДО первой
	// подмены: режимы-переспросы («Точно начать заново?», «Выйти в меню?») временно ставят свои
	// слова, и после отмены вернуть надо именно авторские, а не значения стиля.
	inline void Remember(const UTextBlock* Block, FText& OutSaved)
	{
		OutSaved = Block ? Block->GetText() : FText::GetEmpty();
	}

	// Смешанная строка вида «подпись: значение» (например «Качество картинки: высокое»): половина
	// её — подпись владельца, половина — живые данные. Владелец может задать СВОЮ формулировку
	// прямо в кубике, вставив в него {Value} — тогда шаблоном служит его текст, и подставляем мы
	// только значение. Нет {Value} (обычный текст или наше дерево) — берём формат кода.
	// Запомненный текст брать ДО первой записи: после неё в кубике лежит уже готовая строка.
	inline FText FormatOwned(const FText& SavedOwnerText, const FText& CodeFormat, bool bCodeTreeBuilt)
	{
		return (!bCodeTreeBuilt && SavedOwnerText.ToString().Contains(TEXT("{Value}")))
			? SavedOwnerText : CodeFormat;
	}

	// Вернуть подпись после переспроса. Пусто в запомненном = кубика владельца не было или он
	// был пуст, тогда законно ставим запаску из стиля. В своём кодовом дереве всегда берём
	// запаску: там правда — стиль, и новый ApplyStyle обязан доезжать до экрана.
	inline void Restore(UTextBlock* Block, const FText& Saved, const FText& Fallback, bool bCodeTreeBuilt)
	{
		if (Block)
		{
			Block->SetText((bCodeTreeBuilt || Saved.IsEmpty()) ? Fallback : Saved);
		}
	}
}
