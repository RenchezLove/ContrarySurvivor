#pragma once

#include "CoreMinimal.h"

/**
 * Мост C++ <-> Java к Yandex Mobile Ads SDK: вознаграждаемые ролики, полноэкранный показ
 * без награды (межстраничный) и маленький закреплённый баннер.
 *
 * Здесь НЕТ игровой логики: класс умеет поднять SDK, заказать ролик или полноэкранный показ,
 * показать их, поставить и убрать баннер. Что считать наградой, когда ставить игру
 * на паузу и какие события слать в аналитику — решает UYandexAdService в игровом модуле.
 *
 * Ролики опознаются по идентификатору рекламного места (ad unit id), а не по названию
 * игровой точки: если все три точки игры настроены на один и тот же идентификатор, в памяти
 * висит ОДИН предзагруженный ролик на всех, а не три.
 *
 * Вне Android все методы — пустышки, IsSupported() возвращает false. Так десктопная сборка
 * и редактор собираются и работают без единой заглушки в игровом коде.
 */

enum class EYandexAdEvent : uint8
{
	// SDK поднялся и готов принимать заказы на ролики (AdUnitId пустой).
	Initialized = 0,
	// Ролик загрузился и ждёт показа.
	Loaded = 1,
	// Загрузить не удалось (нет сети, нет заполнения и т.п.) — Detail содержит код и текст.
	LoadFailed = 2,
	// Ролик появился на экране.
	Shown = 3,
	// Техническая ошибка показа уже начатого ролика — Detail содержит текст ошибки.
	ShowFailed = 4,
	// Окно ролика закрылось. Была ли награда — смотреть по пришедшему ранее Rewarded.
	Dismissed = 5,
	// SDK засчитал просмотр и выдал награду.
	Rewarded = 6,
	// Показ заказали, а готового ролика нет. Признак ошибки в логике вызова, не ошибки сети.
	NoAdToShow = 7,
	// Баннер загрузился и встал на экран. Detail — его высота долей высоты окна ("0.1234").
	BannerLoaded = 8,
	// Баннер загрузить не удалось — Detail содержит код и текст; на экране ничего нет.
	BannerLoadFailed = 9,
};

// Полноэкранный показ без награды шлёт ТЕ ЖЕ события, что ролик (Loaded, LoadFailed, Shown,
// ShowFailed, Dismissed, NoAdToShow) — различают их по идентификатору рекламного места:
// у разных форматов идентификаторы разные.

// События приходят УЖЕ В ИГРОВОМ ПОТОКЕ (мост сам перекладывает их с потока Android).
DECLARE_MULTICAST_DELEGATE_ThreeParams(FOnYandexAdEvent, const FString& /*AdUnitId*/, EYandexAdEvent /*Event*/, const FString& /*Detail*/);

class YANDEXADS_API FYandexAdsBridge
{
public:
	// Есть ли под этой платформой реальный SDK. Вне Android — false.
	static bool IsSupported();

	// Поднять SDK. Ответ придёт событием Initialized; повторный вызов безопасен.
	// bUserConsent — согласие пользователя на обработку данных в рекламных целях (GDPR).
	static void Initialize(bool bUserConsent, bool bEnableSdkLogging);

	// Заказать предзагрузку ролика. Повторный заказ, пока ролик грузится или уже лежит
	// готовым, ничего не делает.
	static void LoadRewarded(const FString& AdUnitId);

	// Показать предзагруженный ролик.
	static void ShowRewarded(const FString& AdUnitId);

	// Заказать предзагрузку полноэкранного показа без награды. Правила те же, что у ролика.
	static void LoadInterstitial(const FString& AdUnitId);

	// Показать предзагруженный полноэкранный показ без награды.
	static void ShowInterstitial(const FString& AdUnitId);

	// Поставить баннер: родное окно Android поверх игры, прижатое к НИЖНЕМУ краю экрана.
	// MaxHeightFraction — предельная высота баннера долей высоты экрана. Баннер одновременно
	// один: новый вызов убирает прежний. Пока баннер не загрузился, на экране ничего нет.
	// Событие BannerLoaded несёт в Detail ФАКТИЧЕСКУЮ высоту баннера долей высоты окна
	// (строка вида "0.1234") и может прийти повторно, если высота изменилась.
	static void ShowBanner(const FString& AdUnitId, float MaxHeightFraction);

	// Убрать баннер сразу (в том числе недогруженный). Баннера нет — ничего не делает.
	static void HideBanner();

	// Открыть штатную отладочную панель SDK: она показывает список подхваченных адаптеров
	// медиации с версиями и отмечает проблемы подключения. Нужна ровно для одного —
	// доказать на живом устройстве, что адаптер VK реально попал в сборку, не дожидаясь
	// показа роликов. Вызывается консольной командой "ya.DebugPanel".
	static void ShowDebugPanel();

	static FOnYandexAdEvent& OnAdEvent();
};
